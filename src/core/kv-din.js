// Пересчёт первого СПО между мм Al и мм Cu по качествам серии TH из DIN 6809-4:2020, табл. 5 (СПО даны в обоих
// металлах, определены в 100 см от фокуса). Нужен, когда качества сертификата заданы в одном металле, а СПО клинического
// пучка — в другом: интерполировать k_Q (K, N) по СПО можно только в одном металле (TRS-398 Rev.1, разд. 9.4.4).
//
// Это справочная оценка, а не методика TRS-398 Rev.1: соотношение СПО в Al и в Cu зависит от спектра (разд. 9.3.1 —
// пучок с данным СПО можно получить разными напряжением и фильтрацией), а табл. 5 описывает только спектры TH
// (вольфрамовая трубка, фильтры 4,5–9 мм Al или 4 мм Al + Cu). Пересчёт — линейная интерполяция ln(СПО₂) по ln(СПО₁)
// между соседними качествами TH; вне диапазона табл. 5 — продолжение крайнего отрезка с пометкой «экстраполяция».
// Точность оценена сверкой с качествами, где СПО известны в обоих металлах: TG-61 (Ma et al. 2001), табл. II — M150
// (10,2 мм Al; 0,67 мм Cu), M200 (14,9; 1,69); TRS-398 Rev.1, табл. 53 (МБМВ) — 100 кВ (4,0; 0,15). Отклонения пересчёта:
// +2,8 %, +4,4 % и −4,8 % (tests/kv-din.test.js), отсюда оценка ±5 % по СПО; вне диапазона табл. 5 — хуже.
/** DIN 6809-4:2020, табл. 5: код, напряжение на трубке (кВ), первый СПО в мм Al и в мм Cu. */
export const DIN_TH = [
  { code: 'TH 100', kv: 100, al: 4.63, cu: 0.18 },
  { code: 'TH 120', kv: 120, al: 6.26, cu: 0.29 },
  { code: 'TH 140', kv: 140, al: 8.21, cu: 0.46 },
  { code: 'TH 150', kv: 150, al: 11.2, cu: 0.82 },
  { code: 'TH 200', kv: 200, al: 14.39, cu: 1.59 },
  { code: 'TH 250', kv: 250, al: 16.85, cu: 2.55 },
  { code: 'TH 280', kv: 280, al: 18.7, cu: 3.43 },
  { code: 'TH 300', kv: 300, al: 19.01, cu: 3.59 },
];

/**
 * Возможное относительное отклонение пересчитанного СПО внутри табл. 5 (полуширина, оценка по сверке — см. заголовок).
 * Как стандартная неопределённость — DIN_HVL_DEV/√3 (прямоугольное распределение).
 */
export const DIN_HVL_DEV = 0.05;

/**
 * СПО hvl в металле from ('Al' | 'Cu') → в другом металле. Возвращает { value, to, extrapolated: null | 'below' | 'above',
 * min, max } — min и max: диапазон табл. 5 в исходном металле; value NaN, если hvl не положительное число.
 */
export function dinHvlConvert(hvl, from) {
  const src = from === 'Cu' ? 'cu' : 'al';
  const dst = src === 'al' ? 'cu' : 'al';
  const xs = DIN_TH.map((q) => Math.log(q[src]));
  const ys = DIN_TH.map((q) => Math.log(q[dst]));
  const out = { value: NaN, to: dst === 'cu' ? 'Cu' : 'Al', extrapolated: null, min: DIN_TH[0][src], max: DIN_TH.at(-1)[src] };
  if (!(hvl > 0)) return out;
  const x = Math.log(hvl);
  let i = 0;
  while (i < xs.length - 2 && x > xs[i + 1]) i++;
  if (x < xs[0] - 1e-12) out.extrapolated = 'below';
  else if (x > xs.at(-1) + 1e-12) out.extrapolated = 'above';
  const t = (x - xs[i]) / (xs[i + 1] - xs[i]);
  out.value = Math.exp(ys[i] + t * (ys[i + 1] - ys[i]));
  return out;
}
