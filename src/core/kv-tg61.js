const EPS = 1e-9;
const inside = (xs, x) => x >= xs[0] - EPS && x <= xs[xs.length - 1] + EPS;
const segment = (xs, x) => {
  let i = 0;
  while (i < xs.length - 2 && x > xs[i + 1]) i++;
  return i;
};

/** Линейно по x; вне таблицы — NaN. */
export function linStrict(xs, ys, x) {
  if (!(Number.isFinite(x) && inside(xs, x))) return NaN;
  if (xs.length === 1) return ys[0];
  const i = segment(xs, x);
  const t = (x - xs[i]) / (xs[i + 1] - xs[i]);
  return ys[i] + t * (ys[i + 1] - ys[i]);
}

/** Линейно по ln(x); вне таблицы — NaN. */
export function lnStrict(xs, ys, x) {
  if (!(x > 0 && inside(xs, x))) return NaN;
  const i = segment(xs, x);
  const t = (Math.log(x) - Math.log(xs[i])) / (Math.log(xs[i + 1]) - Math.log(xs[i]));
  return ys[i] + t * (ys[i + 1] - ys[i]);
}

const range = (xs) => [xs[0], xs[xs.length - 1]];

/** Табл. IV: [μen/ρ]w,air в воздухе, СПО в мм Al. */
export function tg61MuenAir(hvl) {
  const value = lnStrict(TG61_T4_AL.hvl, TG61_T4_AL.muen, hvl);
  return Number.isFinite(value) ? { value } : { value: NaN, out: 'hvl', range: range(TG61_T4_AL.hvl) };
}

/**
 * Табл. V: B_w открытого тубуса для СПО (мм Al), РИП и диаметра поля d (см).
 * Внутри строки РИП — по ln(СПО) для каждого d, затем линейно по d; между строками РИП — линейно.
 * Вне таблицы — { value: NaN, out: 'hvl' | 'ssd' | 'd' | 'hvl-short-ssd' }.
 */
export function tg61Bw(hvl, ssd, d) {
  const ssds = Object.keys(TG61_T5_AL).map(Number).sort((a, b) => a - b);
  if (!(hvl > 0 && inside(TG61_T5_HVL_AL, hvl))) return { value: NaN, out: 'hvl', range: range(TG61_T5_HVL_AL) };
  if (!(ssd > 0 && inside(ssds, ssd))) return { value: NaN, out: 'ssd', range: range(ssds) };
  if (!(d > 0 && inside(TG61_T5_D, d))) return { value: NaN, out: 'd', range: range(TG61_T5_D) };
  const atSsd = (s) => {
    const rows = TG61_T5_AL[s];
    const hs = TG61_T5_HVL_AL.slice(0, rows[0].length);
    const byD = rows.map((row) => lnStrict(hs, row, hvl));
    return linStrict(TG61_T5_D, byD, d);
  };
  const i = segment(ssds, ssd);
  const [s0, s1] = [ssds[i], ssds[i + 1]];
  const t = (ssd - s0) / (s1 - s0);
  const need = [t < 1 - EPS ? s0 : null, t > EPS ? s1 : null].filter((s) => s !== null);
  const vals = Object.fromEntries(need.map((s) => [s, atSsd(s)]));
  if (need.some((s) => !Number.isFinite(vals[s]))) return { value: NaN, out: 'hvl-short-ssd', range: [0.04, 4] };
  const v0 = vals[s0] ?? vals[s1];
  const v1 = vals[s1] ?? vals[s0];
  return { value: v0 + t * (v1 - v0) };
}

