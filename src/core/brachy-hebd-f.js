/**
 * F(r,θ) модели источника id по таблице HEBD: билинейная интерполяция по r и θ; r вне таблицы — значение на ближайшем
 * табличном r (HEBD, табл. III). Возвращает { value, extra: '' | 'far' | 'near', table } или null, если таблицы нет.
 */
export function hebdF(id, r, theta) {
  const t = HEBD_F[id];
  if (!t || !Number.isFinite(r) || !Number.isFinite(theta) || theta < 0 || theta > 180) return null;
  const rs = t.r;
  const extra = r > rs[rs.length - 1] ? 'far' : r < rs[0] ? 'near' : '';
  const rc = Math.min(Math.max(r, rs[0]), rs[rs.length - 1]);
  // по r в двух соседних строках θ, затем по θ
  const ths = t.theta;
  let k = ths.findIndex((x) => x >= theta - 1e-12);
  if (k < 0) k = ths.length - 1;
  const row = (i) => interpTable(rs, t.F[i], rc);
  if (Math.abs(ths[k] - theta) < 1e-12 || k === 0) return { value: row(k), extra, table: t.table };
  const a = row(k - 1);
  const b = row(k);
  const value = a + ((theta - ths[k - 1]) / (ths[k] - ths[k - 1])) * (b - a);
  return { value, extra, table: t.table };
}
